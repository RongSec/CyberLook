package scanner

import "sort"

// 启发式端口调度
//
// 背景：自研引擎的派发是「端口外层、目标内层」轮转（见 portscan/scan.go），
// 所以端口列表的顺序**就是**实际发包顺序。全端口扫描时若按 1..65535 顺序发，
// 一台主机的 80/443 要等前 79 个端口探完才轮到；整段 65535 个端口探完需要
// 65535/R 秒（R=单机速率），结果迟迟不出现，人无法中途判断要不要停。
//
// 启发式的第一层做的事：把「高信息量」端口提到前面。
// 它**不减少任何探针**（覆盖范围不变、不漏报），只改变先后 —— 于是：
//   - 前 60 个端口就能判定这台机器是 Windows 还是 Linux、有没有 Web；
//   - 想提前收工的人，几分钟就有 80% 的结论。
//
// 第二层（按服务族定向扩扫）需要引擎支持"扫一段、识别、再决定下一段"，
// 属流水线改造，本版本未做；因此这里的启发式只有排序，不改变扫描集合。
// 这也是为什么 NoSmart 只是"退回原始顺序"，而不是"换一种扫描策略"。

// portPriority 端口 -> 权重。分三档足够：
//
//	100：远程管理入口（22/3389/445/5985）与 Web 主端口（80/443/8080...）
//	 70：常见应用与数据库（3306/6379/9200/1433/5432...）
//	 40：其余"扫到算赚"的常见端口（110/143/993/2049/11211...）
//
// 未列出的端口权重 0，排在三档之后、保持原始数值顺序。
// 权重表按「常见程度 × 信息价值」给，不追求精确 —— 排序只要前几十个对就够。
var portPriority = map[int]int{
	// Web / 反代
	80: 100, 443: 100, 8080: 100, 8443: 100, 8000: 95, 8888: 95,
	8081: 90, 8082: 85, 8880: 85, 9000: 85, 9090: 85, 7001: 85,
	8008: 80, 8009: 80, 8088: 80, 8180: 80, 8181: 80, 9080: 80,
	// 远程管理 / 文件共享（先知道"是什么系统"）
	22: 100, 3389: 100, 445: 100, 139: 90, 135: 90, 5985: 90, 5986: 90,
	23: 85, 21: 85, 5900: 85, 512: 70, 513: 70, 514: 70, 873: 70,
	// 数据库 / 中间件
	3306: 95, 6379: 95, 9200: 95, 1433: 90, 1521: 90, 5432: 90,
	27017: 90, 11211: 85, 5672: 80, 15672: 80, 2181: 80, 9092: 80,
	2375: 85, 2376: 85, 6443: 85, 10250: 80, 8500: 80, 8848: 80,
	// 邮件 / 目录 / 其他
	25: 70, 110: 60, 143: 60, 465: 60, 587: 60, 993: 60, 995: 60,
	389: 75, 636: 75, 88: 75, 3268: 70, 2049: 70, 111: 60, 161: 55,
	69: 55, 123: 40, 179: 55, 500: 55, 4500: 55, 1701: 50, 1723: 50,
	13: 40, 79: 40, 113: 40, 4433: 40, 6667: 40, 9418: 40,
}

// prioritizePorts 按权重降序稳定排序；权重相同保持入参顺序。
//
// 为什么要"稳定"：权重表之外的端口若被打乱，同一任务两次扫描的日志
// （哪个端口先出结果）就不可比，排查时反而添乱。
func prioritizePorts(ports []int) []int {
	if len(ports) <= 1 {
		return ports
	}
	out := make([]int, len(ports))
	copy(out, ports)
	sort.SliceStable(out, func(i, j int) bool {
		return portPriority[out[i]] > portPriority[out[j]]
	})
	return out
}

// highValuePortCount 统计入参里命中权重表的端口数（日志用：让人知道"这一趟前
// 多少个是优先发的"）。
func highValuePortCount(ports []int) int {
	n := 0
	for _, p := range ports {
		if portPriority[p] > 0 {
			n++
		}
	}
	return n
}
